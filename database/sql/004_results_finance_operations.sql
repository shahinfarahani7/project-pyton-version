CREATE TABLE IF NOT EXISTS public.ledger_transactions (
  id uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  workspace_id uuid NOT NULL,
  public_id varchar(32) NOT NULL UNIQUE,
