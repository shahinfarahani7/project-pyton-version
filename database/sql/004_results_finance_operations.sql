  created_at_utc timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ledger_entries_workspace FOREIGN KEY(workspace_id) REFERENCES public.workspaces(id),
  CONSTRAINT FK_ledger_entries_transaction_scope FOREIGN KEY(transaction_id,workspace_id) REFERENCES public.ledger_transactions(id,workspace_id),
  CONSTRAINT FK_ledger_entries_account_scope FOREIGN KEY(account_id,workspace_id) REFERENCES public.ledger_accounts(id,workspace_id),
  CONSTRAINT UQ_ledger_entry_account UNIQUE(transaction_id,account_id)
