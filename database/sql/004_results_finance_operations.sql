BEGIN;

CREATE TABLE IF NOT EXISTS public.results (
  id uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY,
  workspace_id uuid NOT NULL,
  task_attempt_id uuid NOT NULL,
  assignment_id uuid NOT NULL,
  output_file_id uuid NULL,
  inline_output text NULL,
  result_sha256 char(64) NOT NULL,
  worker_signature bytea NOT NULL,
  status varchar(32) NOT NULL,
  created_at_utc timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_results_attempt_scope FOREIGN KEY(task_attempt_id,workspace_id) REFERENCES public.task_attempts(id,workspace_id),
  CONSTRAINT FK_results_assignment_scope FOREIGN KEY(assignment_id,workspace_id) REFERENCES public.assignments(id,workspace_id),
  CONSTRAINT FK_results_file_scope FOREIGN KEY(output_file_id,workspace_id) REFERENCES public.files(id,workspace_id),
  CONSTRAINT CK_results_output CHECK((output_file_id IS NOT NULL AND inline_output IS NULL) OR (output_file_id IS NULL AND inline_output IS NOT NULL)),
  CONSTRAINT UQ_results_scope UNIQUE(id,workspace_id)
);

